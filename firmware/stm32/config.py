# ---------------------------------------------------------------
# 一、测点与 I2C 地址
# ---------------------------------------------------------------
# 每个测点一项：
#   name        测点名称（也是各模块之间传递数据时用的 key）
#   addr        SHT30 的 I2C 地址：0x44（ADDR 接地）或 0x45（ADDR 接电源）。None 表示还没配置
#   mux_channel 使用 TCA9548A 时的通道号 0~7；不经过多路复用器填 None
#
# 待确认：三个模块的实际地址、是否用 TCA9548A。
# SHT30 只有两个地址，第三个测点在硬件方案确定前先留空（None），
# 读取时会明确报告 not_configured，而不是假装有数据。
SENSORS = [
    {"name": "point1", "addr": 0x44, "mux_channel": None},
    {"name": "point2", "addr": 0x45, "mux_channel": None},
    {"name": "point3", "addr": None, "mux_channel": None},
]

# 派生值，不要另外手写，避免与 SENSORS 不一致
POINT_NAMES = [s["name"] for s in SENSORS]
SENSOR_COUNT = len(SENSORS)

# ---------------------------------------------------------------
# 二、I2C 总线
# ---------------------------------------------------------------
# 官方文档：machine.I2C(id, freq, timeout)，引脚不能自定义。
# 待验证：I2C(1) 对应 PB8(SCL)/PB9(SDA)，是根据原理图和手册推断的，上板用 i2c.scan() 确认。
I2C_BUS_ID = 1
I2C_FREQ_HZ = 100000          # 先用 100kHz，稳定后再考虑提高
I2C_TIMEOUT_US = 50000        # 官方默认值 50ms

# ---------------------------------------------------------------
# 三、TCA9548A 多路复用器（待确认是否需要）
# ---------------------------------------------------------------
USE_MUX = False
MUX_ADDR = 0x70               # 待确认：以实际模块的地址跳线为准

# ---------------------------------------------------------------
# 四、SHT30 测量参数（来自 Sensirion 数据手册）
# ---------------------------------------------------------------
# 0x2400：单次测量、高重复性、不带时钟拉伸。
# 不带时钟拉伸是我们的设计选择（STM32 的 MicroPython 是否支持拉伸没有资料）。
SHT30_MEASURE_CMD = (0x24, 0x00)
# 数据手册：高重复性测量最长 15ms，这里留出余量
SHT30_MEASURE_WAIT_MS = 20

# ---------------------------------------------------------------
# 五、采样与滤波（初始值，待实验调整）
# ---------------------------------------------------------------
# 湿度响应约 86 秒（数据手册），采样太快没有意义，滤波窗口也不宜太大
SAMPLE_PERIOD_S = 5
FILTER_WINDOW_SIZE = 5

# ---------------------------------------------------------------
# 六、风险参考阈值（示例值，未经实验验证，不是结论！）
# ---------------------------------------------------------------
# 露点温差：空气温度 - 露点温度。数值越小越接近凝露。
# 注意：SHT30 的误差会让露点温差偏小最多约 0.8°C，阈值要留出余量。
DEW_MARGIN_WARN_C = 5.0       # 示例：低于此值提醒关注
DEW_MARGIN_DANGER_C = 3.0     # 示例：低于此值判为高风险
# 箱内最大温差参考值（注意单个传感器温度误差约 ±0.3°C）
TEMP_DIFF_REF_C = 2.0         # 示例
